#!/bin/bash
# mock-web-eval-probe-port.sh — seed mock-web/.env.mock-web-eval with the
# first free host port in 8080..8089 plus host UID/GID. Idempotent: safe
# to re-run; rewrites the file each invocation. MUST run before any
# `docker compose -f compose.mock-web-eval.yml ...` invocation because the
# compose file uses bare ${HOST_PORT}/${HOST_UID}/${HOST_GID} (no defaults).
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
ENV_FILE="$REPO_ROOT/mock-web/.env.mock-web-eval"
mkdir -p "$(dirname "$ENV_FILE")"

port_in_use() {
  local p="$1"
  if command -v ss >/dev/null 2>&1; then
    ss -ltn 2>/dev/null | awk '{print $4}' | grep -qE "[:.]${p}\$"
  else
    (exec 3<>"/dev/tcp/127.0.0.1/${p}") >/dev/null 2>&1 && return 0 || return 1
  fi
}

CHOSEN=""
for p in $(seq 8080 8089); do
  if ! port_in_use "$p"; then CHOSEN="$p"; break; fi
done

if [ -z "$CHOSEN" ]; then
  echo "[mock-web-eval] ERROR: no free host port in 8080..8089" >&2
  exit 1
fi

cat > "$ENV_FILE" <<EOF
# Auto-generated by scripts/mock-web-eval-probe-port.sh — DO NOT EDIT.
HOST_PORT=${CHOSEN}
HOST_UID=$(id -u)
HOST_GID=$(id -g)
PIPELINE_PROJECT_ROOT=${REPO_ROOT}
PIPELINE_WORKTREE_PATH=${REPO_ROOT}
EOF

echo "[mock-web-eval] wrote ${ENV_FILE} (HOST_PORT=${CHOSEN})"
